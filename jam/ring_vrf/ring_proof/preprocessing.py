# H's Scaled Multiples
def h_vector(Blinding_Base,size=10):
    """
    input: Blinding Base
    output:H_Vector
    """
    #convert B_B into SW point
    Blinding_Base= short_to_te(Blinding_Base)
    H_Vct = []
    for i in range(size):
        New_H_point = point_multiplication(2**i, Blinding_Base)
        H_Vct.append(New_H_point)
    return H_Vct

