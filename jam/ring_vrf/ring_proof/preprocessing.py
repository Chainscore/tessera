def relation_to_prove(k,t,H,Ring_of_pk):
    """
    input:Prover Secret Scalar, Prover index, Blinding Base, Ring_of_pk
    """
    Pk=Ring_of_pk[k]
    R=point_addition(Pk ,point_multiplication(t, H))
    return R


