# selector vector
def selector_vector(Ring_of_pk,size=10):
    """
    input: ring of public key's
    output: selecting vector having 0/1
    """
    s_vector = []
    N_K=size-len(Ring_of_pk)
    for i in range(size):
        if i<N_K:
            s_vector.append(1)
        else:
            s_vector.append(0)
    return s_vector

